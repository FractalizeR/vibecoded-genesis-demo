/**
 * Вычисляет start time для каждой фазы на основе duration
 */
function buildPhases(definitions) {
  let currentStart = 0;
  return definitions.map(def => {
    const phase = {
      ...def,
      start: currentStart
    };
    currentStart += def.duration === Infinity ? 0 : def.duration;
    return phase;
  });
}

